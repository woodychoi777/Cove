import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, mkdir, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { playableFlac } from './fixtures.mjs';
import { openCollectionSong, navigateTo } from './song-ui.mjs';

test('곡 삭제 확인·취소·실제 파일 삭제·현재 재생 정지', { skip: !process.env.RUN_BROWSER_TESTS, timeout: 120000 }, async t => {
  const module = process.env.PLAYWRIGHT_MODULE || 'playwright', { chromium } = await import(module);
  const { expect } = await import(module.startsWith('/') ? pathToFileURL(join(module, '..', 'test.mjs')).href : 'playwright/test');
  const temp = await mkdtemp(join(tmpdir(), 'cove-info-browser-'));
  const out = resolve(process.env.INFO_ARTIFACT_DIR || join(temp, 'evidence')); await mkdir(out, { recursive: true });
  const url = 'http://127.0.0.1:45329';
  const server = spawn(process.execPath, ['src/server.mjs'], { env: { ...process.env, PORT: '45329', SORISEOJAE_DATA_DIR: join(temp, 'data') }, stdio: ['ignore', 'pipe', 'pipe'] });
  t.after(() => server.kill('SIGTERM'));
  let stderr = ''; server.stderr.on('data', chunk => stderr += chunk);
  await new Promise((ok, no) => { const timer = setTimeout(() => no(Error(stderr || 'server timeout')), 10000); server.stdout.on('data', chunk => { if (String(chunk).includes('프로토타입:')) { clearTimeout(timer); ok(); } }); server.on('exit', () => { clearTimeout(timer); no(Error(stderr)); }); });
  const bytes = playableFlac({ title: '삭제 검사', seconds: 20 });
  const staged = await (await fetch(`${url}/api/stage`, { method: 'POST', headers: { 'x-file-name': 'delete.flac' }, body: bytes })).json();
  const track = await (await fetch(`${url}/api/commit`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ importId: staged.importId, metadata: {} }) })).json();
  const snapshot = await (await fetch(`${url}/api/state`)).json();
  assert.equal((await fetch(`${url}/api/tracks/${track.id}`, { method: 'DELETE', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ confirmDeleteFile: true }) })).status, 403);
  assert.equal((await fetch(`${url}/api/tracks/${track.id}`, { method: 'DELETE', headers: { 'Content-Type': 'application/json', 'x-local-token': snapshot.localToken }, body: '{}' })).status, 400);
  const browser = await chromium.launch({ headless: true, channel: 'chrome', args: ['--mute-audio'] }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(url); await navigateTo(page, 'library'); await openCollectionSong(page, track.id);
  await page.locator('#detail-content [data-edit-info]').click(); await page.locator('#track-info-delete').click();
  await expect(page.locator('#delete-track-dialog')).toBeVisible();
  await expect(page.locator('#delete-track-path')).toContainText(track.managedPath);
  await page.screenshot({ path: join(out, 'delete-confirm.png') });
  await page.locator('#delete-track-dialog [data-dialog-close]').click();
  await expect(page.locator('#track-info-dialog')).toBeVisible();
  await expect(page.locator('#track-info-delete')).toBeFocused();
  await page.locator('#track-info-dialog [data-dialog-close]').click();
  assert.deepEqual(await readFile(join(snapshot.libraryRoot, track.managedPath)), bytes);
  await page.locator('#mini-play').click();
  await page.locator('#detail-content [data-edit-info]').click(); await page.locator('#track-info-delete').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(out, 'delete-confirm-small.png') });
  await page.locator('#delete-track-confirm').click();
  await expect(page.locator('#delete-track-dialog')).not.toBeVisible();
  await expect(page.locator('body')).toHaveAttribute('data-route', 'library');
  assert.equal((await fetch(`${url}/api/tracks/${track.id}`)).status, 404);
  await assert.rejects(readFile(join(snapshot.libraryRoot, track.managedPath)), { code: 'ENOENT' });
  const queue = await page.evaluate(() => JSON.parse(localStorage.getItem('soriseojae.queue')));
  assert.deepEqual(queue.ids, []); assert.deepEqual(errors, []);
});
